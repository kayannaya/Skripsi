"""## Pre-processing"""

def has_empty_placeholder(example: dict) -> bool:
    """Detect outputs with unfilled template placeholders e.g. 'melibatkan .' or 'menjadi ,'"""
    text = example.get("output", "")
    patterns = [
        r"melibatkan\s*\.",
        r"menjadi\s*,",
        r"berkembang menjadi\s*[,.]",
        r"yang melibatkan\s*[,.]",
    ]
    return any(re.search(p, text) for p in patterns)


def filter_data(data: list[dict]) -> list[dict]:
    filtered = [ex for ex in data if not has_empty_placeholder(ex)]
    print(f"Removed {len(data) - len(filtered)} examples with empty placeholders")
    print(f"Remaining: {len(filtered)} examples")
    return filtered


def format_example(example: dict) -> dict:
    """
    Format a PICO dict into ChatML format.
    SFTTrainer masks the prompt tokens so loss is computed only on the assistant response.
    """
    user_message = f"{example['instruction']}\n\n{example['input']}"
    text = (
        f"<|im_start|>user\n{user_message}<|im_end|>\n"
        f"<|im_start|>assistant\n{example['output']}<|im_end|>"
    )
    return {"text": text}

"""# Model"""

def load_model_and_tokenizer():
    print("Loading model...")
    bnb_config = BitsAndBytesConfig(
        load_in_4bit= True,
        bnb_4bit_compute_dtype = torch.bfloat16,
        bnb_4bit_quant_type = "nf4",
        bnb_4bit_use_double_quant = True,
    )
    model = AutoModelForCausalLM.from_pretrained(
        MODEL_PATH,
        device_map = "auto",
        quantization_config = bnb_config,
        torch_dtype = torch.bfloat16,
    )

    print("Loading tokenizer...")
    tokenizer = AutoTokenizer.from_pretrained(MODEL_PATH, use_fast=True)

    # add chat markers without overwriting the EOS token
    tokenizer.add_special_tokens(
        {"additional_special_tokens": ["<|im_start|>", "<|im_end|>"]}
    )

    # add a dedicated pad token
    if tokenizer.pad_token is None:
        tokenizer.add_special_tokens({"pad_token": "<|pad|>"})

    tokenizer.padding_side = "right"  # SFFT trainer requirement

    # resize embeddings to cover new tokens
    model.resize_token_embeddings(len(tokenizer))

    print(f"Pad token : {tokenizer.pad_token!r} (id={tokenizer.pad_token_id})")
    print(f"EOS token : {tokenizer.eos_token!r} (id={tokenizer.eos_token_id})")
    print(f"Vocab size: {len(tokenizer)}")
    return model, tokenizer

